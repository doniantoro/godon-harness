package golang

import (
	"os"
	"path/filepath"
	"reflect"
	"testing"

	"github.com/doniantoro/godon-harness/internal/driver"
)

const fixture = `package shop

const Amount = 1

var Total int

type Poster interface {
	Post(id string) error
}

type Order struct {
	Amount int
	Post   string
}

type Client struct{}

func (c *Client) Post(id string) error { return nil }

func Post() {}
`

func writeFile(t *testing.T, root, rel, body string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestFindSymbols(t *testing.T) {
	root := t.TempDir()
	writeFile(t, root, "go.mod", "module example.com/m\n")
	writeFile(t, root, "shop/shop.go", fixture)
	writeFile(t, root, "shop/shop_test.go", "package shop\n\nfunc Post2() {}\nfunc helperPost() {}\nvar Post3 = 1\nfunc init() { _ = Post3 }\n\nfunc Post_() {}\n")
	writeFile(t, root, "shop/mocks/mock.go", "package mocks\n\nfunc Post() {}\n")
	writeFile(t, root, "vendor/x/x.go", "package x\n\nfunc Post() {}\n")

	type hit struct {
		File, Qualified, Kind string
	}
	find := func(q driver.SymbolQuery) []hit {
		t.Helper()
		got, err := New().FindSymbols(root, q)
		if err != nil {
			t.Fatal(err)
		}
		var out []hit
		for _, s := range got {
			out = append(out, hit{s.File, s.Qualified(), s.Kind})
		}
		return out
	}

	tests := []struct {
		name string
		q    driver.SymbolQuery
		want []hit
	}{
		{
			name: "every declaration kind under one name, vendor and mocks excluded",
			q:    driver.SymbolQuery{Name: "Post"},
			want: []hit{
				{"shop/shop.go", "Poster.Post", "method"},
				{"shop/shop.go", "Order.Post", "field"},
				{"shop/shop.go", "Client.Post", "method"},
				{"shop/shop.go", "Post", "func"},
			},
		},
		{
			name: "Type.Name keeps one owner",
			q:    driver.SymbolQuery{Name: "Post", Owner: "Client"},
			want: []hit{{"shop/shop.go", "Client.Post", "method"}},
		},
		{
			name: "const and field share a name",
			q:    driver.SymbolQuery{Name: "Amount"},
			want: []hit{{"shop/shop.go", "Amount", "const"}, {"shop/shop.go", "Order.Amount", "field"}},
		},
		{
			name: "--tests includes generated mocks",
			q:    driver.SymbolQuery{Name: "Post", Owner: "", IncludeTests: true, Path: "shop/mocks"},
			want: []hit{{"shop/mocks/mock.go", "Post", "func"}},
		},
		{
			name: "an unknown name finds nothing",
			q:    driver.SymbolQuery{Name: "Missing"},
			want: nil,
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := find(tc.q); !reflect.DeepEqual(got, tc.want) {
				t.Fatalf("got %v, want %v", got, tc.want)
			}
		})
	}
}

func TestSplitArgs(t *testing.T) {
	got := splitArgs(`mockgen -source=a.go "-destination=mocks/a b.go" -package mocks`)
	want := []string{"mockgen", "-source=a.go", "-destination=mocks/a b.go", "-package", "mocks"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("splitArgs = %q, want %q", got, want)
	}
}

func TestIsGenerated(t *testing.T) {
	if !isGenerated([]byte("// Code generated by MockGen. DO NOT EDIT.\npackage m\n")) {
		t.Fatal("generated header not recognised")
	}
	if isGenerated([]byte("package m\n// Code generated by MockGen. DO NOT EDIT.\n")) {
		t.Fatal("a header after the package clause does not mark a file generated")
	}
}
