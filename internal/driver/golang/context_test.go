// contextFixture is a small module shaped like a service with consumer-side
// interfaces: the handler reaches the service only through types.Validator.
func contextFixture(t *testing.T) string {
	t.Helper()
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("go not installed")
	}
	root := t.TempDir()
	files := map[string]string{
		"go.mod": "module example.com/shop\n\ngo 1.24\n",
		"types/types.go": `package types

type AccountGetter interface {
	GetAccount(id string) (string, error)
}

type Validator interface {
	Validate(id string) error
}
`,
		"types/mocks/mock.go": `// Code generated by MockGen. DO NOT EDIT.
package mocks

import "example.com/shop/types"

type MockValidator struct{}

func (MockValidator) Validate(string) error { return nil }

var _ types.Validator = MockValidator{}
`,
		"repo/repo.go": `package repo

type Repo struct{}

func (r *Repo) GetAccount(id string) (string, error) { return id, nil }

func Validate() {}
`,
		"service/service.go": `package service

import (
	"errors"

	"example.com/shop/types"
)

type Service struct {
	accounts types.AccountGetter
}

func New(a types.AccountGetter) *Service { return &Service{accounts: a} }

// Validate checks the account.
func (s *Service) Validate(id string) error {
	acc, err := s.accounts.GetAccount(id)
	if err != nil {
		return err
	}
	if acc == "" {
		return errors.New("empty")
	}
	return helper(acc)
}

func helper(string) error { return nil }

// Run is a caller inside a package that has tests, so its file is parsed
// twice: once for the package, once for its test variant.
func Run(
	s *Service,
) error {
	return s.Validate("x")
}
`,
		"service/service_test.go": `package service

import "testing"

func Describe(_ string, f func()) bool { f(); return true }
func It(_ string, f func())            { f() }

var _ = Describe("Service", func() {
	It("rejects an empty account", func() {
		_ = (&Service{}).Validate("")
	})
})

func TestValidate(t *testing.T) {
	if err := New(nil).Validate("x"); err == nil {
		t.Log("ok")
	}
}
`,
		"handler/handler.go": `package handler

import "example.com/shop/types"

type Handler struct {
	v types.Validator
}

func (h Handler) Handle(id string) error {
	return h.v.Validate(id)
}
`,
		"broken/broken.go": "package broken\n\nfunc X() int { return \"s\" }\n",
	}
	for rel, body := range files {
		writeFile(t, root, rel, body)
	}
	return root
}

func refNames(refs []driver.Ref) []string {
	var out []string
	for _, r := range refs {
		out = append(out, r.Name)
	}
	return out
}

func hasRef(refs []driver.Ref, name string) (driver.Ref, bool) {
	for _, r := range refs {
		if r.Name == name {
			return r, true
		}
	}
	return driver.Ref{}, false
}

func TestContextMethod(t *testing.T) {
	root := contextFixture(t)
	c, err := New().Context(context.Background(), root, driver.ContextQuery{Name: "Validate", Owner: "Service"})
	if err != nil {
		t.Fatal(err)
	}
	if !c.Found || c.Symbol.Qualified() != "Service.Validate" || c.Loc.File != "service/service.go" {
		t.Fatalf("symbol = %+v at %+v", c.Symbol, c.Loc)
	}
	if c.Loc.Line != 15 || c.Loc.EndLine != 25 {
		t.Errorf("range = %d-%d, want 15-25 (doc comment through closing brace)", c.Loc.Line, c.Loc.EndLine)
	}
	if !strings.Contains(c.Signature, "func (s *Service) Validate(id string) error") {
		t.Errorf("signature = %q", c.Signature)
	}
	if _, ok := hasRef(c.Implements, "types.Validator.Validate"); !ok {
		t.Errorf("implements = %v", refNames(c.Implements))
	}
	for _, want := range []string{"types.AccountGetter.GetAccount", "service.helper"} {
		if _, ok := hasRef(c.Deps, want); !ok {
			t.Errorf("deps lack %s: %v", want, refNames(c.Deps))
		}
	}
	if !slices.Contains(c.External, "errors") {
		t.Errorf("external = %v", c.External)
	}

	if _, ok := hasRef(c.Callers, "service.Run"); !ok {
		t.Errorf("callers = %v, want service.Run from the package's own file", refNames(c.Callers))
	}
	caller, ok := hasRef(c.Callers, "handler.Handler.Handle")
	if !ok || caller.Via != "types.Validator" || caller.Loc.File != "handler/handler.go" {
		t.Errorf("callers = %+v, want handler.Handler.Handle via types.Validator", c.Callers)
	}
	for _, r := range c.Callers {
		if strings.Contains(r.Loc.File, "mocks/") || strings.HasSuffix(r.Loc.File, "_test.go") {
			t.Errorf("caller from a mock or a test: %+v", r)
		}
	}

	var notes []string
	for _, r := range c.Tests {
		notes = append(notes, r.Note)
	}
	for _, want := range []string{"rejects an empty account", "TestValidate"} {
		if !slices.Contains(notes, want) {
			t.Errorf("tests lack %q: %+v", want, c.Tests)
		}
	}

	// The one-line helper right after the method folds into its range.
	if len(c.Reads) == 0 || c.Reads[0] != (driver.Loc{File: "service/service.go", Line: 15, EndLine: 27}) {
		t.Errorf("reads = %+v, want service/service.go:15-27 first", c.Reads)
	}
	if !slices.ContainsFunc(c.Warnings, func(w string) bool { return strings.Contains(w, "example.com/shop/broken") }) {
		t.Errorf("warnings = %v, want the package that does not build", c.Warnings)
	}
}

func TestContextInterfaceAndType(t *testing.T) {
	root := contextFixture(t)
	iface, err := New().Context(context.Background(), root, driver.ContextQuery{Name: "AccountGetter"})
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := hasRef(iface.Implementations, "repo.Repo"); !ok {
		t.Errorf("implementations = %v", refNames(iface.Implementations))
	}
	if _, ok := hasRef(iface.Methods, "types.AccountGetter.GetAccount"); !ok {
		t.Errorf("methods = %v", refNames(iface.Methods))
	}
	if _, ok := hasRef(iface.Callers, "service.New"); !ok {
		t.Errorf("callers = %v", refNames(iface.Callers))
	}

	typ, err := New().Context(context.Background(), root, driver.ContextQuery{Name: "Repo"})
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := hasRef(typ.Methods, "repo.Repo.GetAccount"); !ok {
		t.Errorf("methods = %v", refNames(typ.Methods))
	}
	if _, ok := hasRef(typ.Implements, "types.AccountGetter"); !ok {
		t.Errorf("implements = %v", refNames(typ.Implements))
	}
}

func TestContextResolvesTheDeclaration(t *testing.T) {
	root := contextFixture(t)
	ctx := context.Background()

	amb, err := New().Context(ctx, root, driver.ContextQuery{Name: "Validate"})
	if err != nil {
		t.Fatal(err)
	}
	// The interface method is dropped in favour of what implements it; two
	// concrete declarations remain and the caller must choose.
	if amb.Found || len(amb.Candidates) != 2 {
		t.Fatalf("found=%v candidates=%+v, want 2 candidates", amb.Found, amb.Candidates)
	}

	byPath, err := New().Context(ctx, root, driver.ContextQuery{Name: "Validate", Path: "service"})
	if err != nil {
		t.Fatal(err)
	}
	if !byPath.Found || byPath.Symbol.Qualified() != "Service.Validate" {
		t.Fatalf("path filter = %+v", byPath.Symbol)
	}

	run, err := New().Context(ctx, root, driver.ContextQuery{Name: "Run"})
	if err != nil || run.Signature != "func Run(s *Service) error" {
		t.Fatalf("multi-line signature = %q, %v", run.Signature, err)
	}

	missing, err := New().Context(ctx, root, driver.ContextQuery{Name: "Nope"})
	if err != nil || missing.Found || len(missing.Candidates) != 0 {
		t.Fatalf("unknown name = %+v, %v", missing, err)
	}
}
